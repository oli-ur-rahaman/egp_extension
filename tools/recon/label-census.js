// @ts-nocheck
// Writes tests/fixtures/label-census.json: every field label the format study saw, per flow, with how many pages carried it.
// Labels and counts only. The test suite checks that the Site Profile accounts for every one.
//   node tools/recon/label-census.js
// Needs recon/raw/study/ on this PC. The output is committed, so the test runs on either PC.

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const clean = (l) => l.replace(/\s+/g, ' ').trim();
// The study keeps any cell ending in a colon. A few are page values, not labels, and must not reach this public repo.
const NOT_A_LABEL = /^memo no\b|\d{2}\.\d{2}\.\d{4}/i;

const samples = ['logged-out', 'logged-in', 'logged-out-pwd'].flatMap((run) => {
  const file = path.join(root, 'recon', 'raw', 'study', run, 'samples.jsonl');
  if (!existsSync(file)) throw new Error(`Missing ${file}: run this on the PC that holds the study.`);
  return readFileSync(file, 'utf8').trim().split('\n').map((line) => JSON.parse(line));
});

const census = { note: 'Generated by tools/recon/label-census.js from the R8 format study. Labels and page counts only.', flows: {} };
for (const flow of ['2', '3', '4', '5']) {
  const pages = samples.filter((s) => s.flow === flow);
  const tally = (key) => {
    const counts = {};
    for (const page of pages) {
      for (const label of new Set(page[key].map(clean).filter(Boolean))) {
        if (!NOT_A_LABEL.test(label)) counts[label] = (counts[label] ?? 0) + 1;
      }
    }
    return Object.fromEntries(Object.entries(counts).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])));
  };
  census.flows[flow] = { pages: pages.length, labels: tally('visible'), tableHeaders: tally('tableHeaders') };
}
const out = path.join(root, 'tests', 'fixtures', 'label-census.json');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(census, null, 2) + '\n');
console.log('Wrote', path.relative(root, out), Object.entries(census.flows).map(([f, c]) => `flow ${f}: ${c.pages} pages`).join(', '));
